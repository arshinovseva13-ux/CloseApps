import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import pngToIco from 'png-to-ico';
const root = process.cwd();
const out = path.join(root, 'www');
await fs.mkdir(out, {recursive:true});
const source = path.resolve(root, '../../sea-battle.html');
const html = await fs.readFile(source, 'utf8');
await fs.writeFile(path.join(out, 'index.html'), html.replace('<title>CLOSE SEA BATTLE — Морской бой</title>','<title>Close Sea Battle</title>'));
const svg = await fs.readFile(path.join(root,'assets','sea-battle.svg'));
const png = await sharp(svg).resize(512,512).png().toBuffer();
await fs.writeFile(path.join(root,'assets','icon.png'), png);
await fs.writeFile(path.join(root,'assets','icon.ico'), await pngToIco(png));
await fs.mkdir(path.join(out,'assets'),{recursive:true});
await fs.copyFile(path.join(root,'assets','sea-battle.svg'),path.join(out,'assets','sea-battle.svg'));
console.log('Prepared web app and app icons.');
